import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {searchMaterials,saveMaterialSearch} from '../plugin/src/material-search.ts';
import {DEFAULT_PROJECT_FOLDERS as folders} from '../plugin/src/settings.ts';
import {syncStructure} from '../plugin/src/story-structure.ts';
import {configPath,fingerprint} from '../plugin/src/narrative-context.ts';
import {withContext,withMaterialSearch,withoutMaterialSearch} from '../plugin/src/request-context.ts';
import {withChanges,withoutChanges} from '../plugin/src/workshop.ts';
import {authorPrompt} from '../plugin/src/conversation.ts';
import {buildSceneContext} from '../plugin/src/scene-context.ts';
import {readEditorialContext} from '../plugin/src/editorial-context.ts';
import {markPopulated,newModelSources} from '../plugin/src/populate-state.ts';
import {selectionPrompt,selectionRequest} from '../plugin/src/selection-actions.ts';

export async function checkMaterialSearch(){
 const root=await mkdtemp(join(tmpdir(),'orelius-material-search-'));
 const put=async(path,content)=>{await mkdir(join(root,path,'..'),{recursive:true});await writeFile(join(root,path),content);};
 const request='Pourquoi la serrure a-t-elle été remplacée après le cambriolage ?';
 const relevant='Bible/Objects/dossier-17.md',irrelevant='Bible/Objects/recette.md',chapter='Manuscript/002.md';
 try {
  await put(relevant,'# Rapport\n\nAprès le cambriolage, la serrure du garage a été remplacée par Nora.');
  await put(irrelevant,'Farine, levure et sucre.');
  await put('Archives/secret.md','Serrure cambriolage : NE PAS TRANSMETTRE.');
  let result=await searchMaterials(root,folders,request);
  assert.equal(result.matches[0].path,relevant,'Le contenu est trouvé même si le nom du fichier ne correspond pas.');
  assert.ok(result.matches[0].excerpts.join('').includes('Nora'));
  assert.ok(!result.matches.some(match=>match.path===irrelevant || match.path.startsWith('Archives/')));
  const wire=withMaterialSearch(withChanges(request,{pending:[{path:relevant,kind:'modifié',hash:'x'}]}),result);
  assert.equal(authorPrompt(wire),request);assert.equal(withoutChanges(wire),request);
  assert.equal(withoutMaterialSearch(withMaterialSearch(request,result)),request);
  await saveMaterialSearch(root,folders,result,()=>{});
  assert.ok((await readFile(join(root,'Tracking/Recherche.md'),'utf8')).includes(relevant));
  let pages=await readEditorialContext(root,folders,{},undefined,request);
  assert.ok(pages.join('').includes('Nora'),'Recherche utilisée sans chapitre actif.');
  await put(chapter,'(((Vérifier le cambriolage et la serrure avant de reprendre.)))');
  let scene=await buildSceneContext(root,folders,{},chapter,'Recommence.');
  assert.ok(scene.sources.some(source=>source.path===relevant),'Les annotations du chapitre orientent une demande courte.');
  result=await searchMaterials(root,folders,withContext(request,{chapter:null,include:[],exclude:[relevant]}));
  assert.ok(!result.matches.some(match=>match.path===relevant));
  await put(configPath(folders),'```json\n'+JSON.stringify({chapters:[],references:[{path:relevant,hiddenSections:['Secret']} ]})+'\n```');
  await put(relevant,'# Rapport\n\nSerrure réparée.\n\n## Secret\n\nCambriolage : CODE_SECRET.');
  result=await searchMaterials(root,folders,request);
  assert.ok(!JSON.stringify(result).includes('CODE_SECRET'));
  await put(configPath(folders),'```json\n'+JSON.stringify({chapters:[],references:[{path:relevant,mode:'hidden'}]})+'\n```');
  result=await searchMaterials(root,folders,request);
  assert.ok(!result.matches.some(match=>match.path===relevant));
  await put(configPath(folders),'```json\n'+JSON.stringify({chapters:[],references:[]})+'\n```');
  await put(relevant,'Préambule banal. '.repeat(1000)+' La serrure du garage explique le cambriolage.');
  result=await searchMaterials(root,folders,request);
  assert.ok(result.matches.find(match=>match.path===relevant).excerpts.join('').includes('serrure'),'Un résultat en fin de long paragraphe reste dans l’extrait.');
  await put(relevant,'La serrure a été changée par Léa après le cambriolage.');
  await assert.rejects(saveMaterialSearch(root,folders,result,()=>{}),/Source modifiée/);
  result=await searchMaterials(root,folders,request);
  assert.equal(result.matches.find(match=>match.path===relevant).hash,fingerprint(await readFile(join(root,relevant),'utf8')));
  assert.ok(result.matches.find(match=>match.path===relevant).excerpts.join('').includes('Léa'));
  const selection=selectionPrompt(selectionRequest('reformuler',chapter,'La serrure.',0,11));
  result=await searchMaterials(root,folders,selection+'\n\nRecherche aussi le cambriolage.',chapter);
  assert.ok(result.query.includes('cambriolage'));
  await rm(join(root,relevant));
  result=await searchMaterials(root,folders,request);
  assert.ok(!result.matches.some(match=>match.path===relevant),'Une suppression est prise en compte dès la demande suivante.');
  await put('Model/ancien.md','Cambriolage, serrure : ancien document.');
  await markPopulated(root,folders,await newModelSources(root,folders),()=>{});
  await put('Model/ancien.md','Cambriolage, serrure : ajout ancien à ignorer pour Peupler.');
  await put('Model/nouveau.md','Cambriolage, serrure : nouveau document.');
  result=await searchMaterials(root,folders,request,undefined,true);
  assert.ok(result.matches.some(match=>match.path==='Model/ancien.md'),'Une source modifiée est de nouveau recherchée pour Peupler.');
  assert.ok(result.matches.some(match=>match.path==='Model/nouveau.md'));

  await put('Bible/Seeds/cause.md','Cambriolage : motivation retenue.');
  await put('Bible/Plan/consequence.md','Un départ en train.');
  let structure=await syncStructure(root,folders);
  const from=structure.nodes.find(node=>node.path==='Bible/Seeds/cause.md'),to=structure.nodes.find(node=>node.path==='Bible/Plan/consequence.md');
  await syncStructure(root,folders,{link:{from:from.id,to:to.id,relation:'developpe',fromHash:from.hash,toHash:to.hash}});
  result=await searchMaterials(root,folders,request);
  assert.ok(result.matches.some(match=>match.path===to.path && match.reasons.some(reason=>reason.includes('Relation'))));
  await syncStructure(root,folders,{decision:{path:to.path,value:'abandonne'}});
  result=await searchMaterials(root,folders,request);
  assert.ok(!result.matches.some(match=>match.path===to.path));
  await put(configPath(folders),'```json\n'+JSON.stringify({chapters:[],references:[],referenceBudget:1000})+'\n```');
  for(let index=0;index<15;index++) await put(`Bible/Objects/limite-${index}.md`,'Serrure et cambriolage. '.repeat(100));
  result=await searchMaterials(root,folders,request);
  assert.ok(result.matches.flatMap(match=>match.excerpts).reduce((sum,text)=>sum+text.length,0)<=1000);
  assert.ok(result.omitted.length>0,'Les sources hors budget restent signalées.');
  result=await searchMaterials(root,folders,'Zygomatique');
  assert.ok(result.unmatched.includes('zygomatique'));
  await put('Tracking/Connaissances.md','## Consignes actives\n\nLe métronome donne la cadence.\n\n## Historique\n\nMétronome : ANCIENNE_HYPOTHESE.');
  result=await searchMaterials(root,folders,'Métronome');
  assert.ok(result.matches.some(match=>match.path==='Tracking/Connaissances.md'),'Les enseignements actifs restent recherchables hors de Bible.');
  assert.equal(JSON.stringify(result).includes('ANCIENNE_HYPOTHESE'),false);
  await put('Tracking/Connaissances.md','# Historique\n\nMétronome : CONSIGNE_REMPLACEE.');
  result=await searchMaterials(root,folders,'Métronome');
  assert.equal(JSON.stringify(result).includes('CONSIGNE_REMPLACEE'),false,'Un historique sans rubrique active n’est pas une consigne actuelle.');
  pages=await readEditorialContext(root,folders,{},undefined,'Métronome');
  assert.equal(pages.join('').includes('CONSIGNE_REMPLACEE'),false);
  await put(configPath(folders),'```json\n'+JSON.stringify({chapters:[],references:[]})+'\n```');
  await put('Model/Aout/001.md','# Ouverture\n\nLa lettre accompagne les funérailles.');
  await put('Model/Septembre/lettre-funerailles.md','# Lettre\n\n'+('La lettre évoque les funérailles.\n'.repeat(30)));
  result=await searchMaterials(root,folders,'Travaillons sur août, la lettre des funérailles.');
  assert.equal(result.matches[0].path,'Model/Aout/001.md','Le dossier nommé dans la demande doit orienter la recherche avant une répétition thématique ailleurs.');

 }finally{await rm(root,{recursive:true,force:true});}
}
