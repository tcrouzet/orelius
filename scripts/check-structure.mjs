import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rename, rm, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { syncStructure, structurePath, structureView, parseStructure } from '../plugin/src/story-structure.ts';
import { projectSources } from '../plugin/src/project-sources.ts';
import { changeImpacts } from '../plugin/src/change-impact.ts';
import { collectChanges, deliverChanges } from '../plugin/src/workshop.ts';
import { buildSceneContext, checkSceneContext } from '../plugin/src/scene-context.ts';
import { DEFAULT_PROJECT_FOLDERS as folders } from '../plugin/src/settings.ts';
import { ProjectMcp, STRUCTURE_TOOL, LINK_TOOL } from '../plugin/src/mcp.ts';

export async function checkStructure() {
 const root = await mkdtemp(join(tmpdir(), 'orelius-structure-'));
 const put = async (path, text) => { await mkdir(join(root, path, '..'), { recursive: true }); await writeFile(join(root, path), text); };
 const paths = { seed: 'Manuscript/Seeds/depart.md', plan: 'Manuscript/Plan/002.md', scene: 'Manuscript/Scenes/cuisine.md', character: 'Bible/Personnages/Louise.md', plot: 'Manuscript/Intrigues/video.md', chapter: 'Manuscript/Chapitres/002.md' };
 let server;
 try {
  for (const [name,path] of Object.entries(paths)) await put(path, name === 'chapter' ? 'Louise ouvre la porte. Nadia entre.' : name + ' initial');
  await put('Manuscript/Seeds/index.md', 'Index');
  let data = await syncStructure(root, folders);
  assert.equal(data.nodes.length, 6);
  const ids = Object.fromEntries(Object.entries(paths).map(([key,path])=>[key,data.nodes.find(node=>node.path===path).id]));
  const node = key => data.nodes.find(node=>node.id===ids[key]);
  assert.ok(data.nodes.every(node=>node.decision==='propose'));
  const initial = await readFile(join(root,structurePath(folders)), 'utf8');
  await syncStructure(root, folders);
  assert.equal(await readFile(join(root,structurePath(folders)), 'utf8'), initial, 'Consultation idempotente.');
  await put(paths.seed, 'Intention humaine modifiée.');
  data = await syncStructure(root,folders,{decision:{path:paths.seed,value:'retenu'}});
  assert.equal(node('seed').decision,'retenu');
  assert.equal(node('seed').id,ids.seed);
  const args=(from,to,relation,extra={})=>({from:ids[from],to:ids[to],relation,fromHash:node(from).hash,toHash:node(to).hash,...extra});
  for(const [from,to,relation,extra] of [['seed','plan','developpe'],['plan','scene','planifie'],['character','scene','implique'],['plot','scene','implique'],['scene','chapter','realise',{quote:'Nadia entre.',at:23}]]) data=await syncStructure(root,folders,{link:args(from,to,relation,extra)});
  assert.ok(structureView(data,await projectSources(root,folders)).links.every(link=>link.status==='valide'));
  await assert.rejects(()=>syncStructure(root,folders,{link:args('seed','chapter','planifie')}),/invalide/);
  await assert.rejects(()=>syncStructure(root,folders,{link:args('scene','chapter','realise',{quote:'Nadia entre.',at:0})}),/passage|Citation/);
  await assert.rejects(()=>syncStructure(root,folders,{link:args('seed','plan','developpe',{decision:'retenu'})}),/invalides/);
  await assert.rejects(()=>syncStructure(root,folders,{link:{...args('seed','plan','developpe'),fromHash:'a'.repeat(64)}}),/modifiées/);
  const context=await buildSceneContext(root,folders,{},paths.chapter);
  assert.ok(context.sources.some(source=>source.role==='structured-decisions-and-links-not-canon'&&source.content.includes(ids.scene)&&source.content.includes('retenu')));
  await deliverChanges(root,folders,await collectChanges(root,folders));
  await put(paths.seed,'Autre intention humaine.');
  const changes=await collectChanges(root,folders);
  const impacts=changes.pending.find(change=>change.path===paths.seed).affected;
  assert.ok(impacts.some(item=>item.path===paths.chapter&&item.chain.some(link=>link.excerpt.includes('developpe'))));
  await assert.rejects(()=>checkSceneContext(root,context),/Source modifiée/);
  data=await syncStructure(root,folders);
  assert.equal(node('seed').decision,'retenu');
  assert.equal(structureView(data,await projectSources(root,folders)).links.find(link=>link.from===ids.seed).status,'à revalider');
  data=await syncStructure(root,folders,{link:args('seed','plan','developpe')});
  await put(paths.chapter,'Avant. Louise ouvre la porte. Nadia entre.');
  data=await syncStructure(root,folders);
  assert.equal(structureView(data,await projectSources(root,folders)).links.find(link=>link.relation==='realise').status,'valide','Citation unique déplacée conservée.');
  await put(paths.chapter,'Nadia entre. Nadia entre.');
  data=await syncStructure(root,folders);
  assert.equal(structureView(data,await projectSources(root,folders)).links.find(link=>link.relation==='realise').status,'à revalider','Citation devenue ambiguë.');
  data=await syncStructure(root,folders,{link:args('scene','chapter','realise',{quote:'Nadia entre.',at:13})});
  await put(paths.chapter,'Nadia sort.');
  data=await syncStructure(root,folders);
  assert.equal(structureView(data,await projectSources(root,folders)).links.find(link=>link.relation==='realise').status,'à revalider');
  const renamed='Manuscript/Scenes/renommee.md';
  await rename(join(root,paths.scene),join(root,renamed));
  await put(renamed,'Scène aussi modifiée.');
  data=await syncStructure(root,folders,{rename:{from:paths.scene,to:renamed}});
  assert.equal(node('scene').path,renamed);
  assert.equal(data.links.find(link=>link.relation==='realise').from,ids.scene);
  const moved='Bible/Personnages/Louise-renommee.md';
  await rename(join(root,paths.character),join(root,moved));
  data=await syncStructure(root,folders);
  assert.equal(node('character').path,moved,'Renommage hors Obsidian, contenu unique identique.');
  await put('Bible/Personnages/copie.md',await readFile(join(root,moved),'utf8'));
  data=await syncStructure(root,folders);
  assert.notEqual(data.nodes.find(node=>node.path.endsWith('/copie.md')).id,ids.character);
  await rm(join(root,moved));
  data=await syncStructure(root,folders);
  assert.equal(node('character').missing,true);
  await put('Manuscript/Seeds/doublon-a.md','Même texte'); await put('Manuscript/Seeds/doublon-b.md','Même texte');
  data=await syncStructure(root,folders);
  const originals=data.nodes.filter(node=>node.path.includes('doublon-')).map(node=>node.id);
  await rename(join(root,'Manuscript/Seeds/doublon-a.md'),join(root,'Manuscript/Seeds/autre-a.md'));
  await rename(join(root,'Manuscript/Seeds/doublon-b.md'),join(root,'Manuscript/Seeds/autre-b.md'));
  data=await syncStructure(root,folders);
  assert.ok(data.nodes.filter(node=>originals.includes(node.id)).every(node=>node.missing),'Renommage ambigu non inventé.');
  data=await syncStructure(root,folders,{decision:{path:paths.seed,value:'abandonne'}});
  assert.equal(structureView(data,await projectSources(root,folders)).links.find(link=>link.relation==='developpe').status,'abandonné');
  await assert.rejects(()=>syncStructure(root,folders,{link:args('seed','plan','developpe')}),/abandonné/);
  const missingSceneSources=(await projectSources(root,folders)).filter(source=>source.path!==renamed);
  const missingScene=structuredClone(data);missingScene.nodes.find(node=>node.id===ids.scene).missing=true;
  assert.ok(changeImpacts(missingSceneSources,folders,[paths.seed],[],missingScene).get(paths.seed).some(item=>item.path===paths.chapter),'Dépendances conservées même après disparition d’une scène intermédiaire.');
  await deliverChanges(root,folders,await collectChanges(root,folders));
  data=await syncStructure(root,folders,{decision:{path:paths.seed,value:'propose'}});
  const resetDecision=await collectChanges(root,folders);
  assert.equal(resetDecision.pending.find(change=>change.path===structurePath(folders)).kind,'modifié');
  const graphSources=await projectSources(root,folders);
  graphSources.push({path:structurePath(folders),content:await readFile(join(root,structurePath(folders)),'utf8'),hash:'f'.repeat(64)});
  const characterImpacts=changeImpacts(graphSources,folders,[paths.plot],[],data).get(paths.plot);
  assert.equal(characterImpacts.some(item=>item.path===paths.seed),false,'Le registre ne diffuse pas un changement vers les autres branches du graphe.');
  data=await syncStructure(root,folders,{link:args('character','scene','implique',{remove:true})});
  assert.equal(data.links.some(link=>link.from===ids.character),false,'Un lien vers une fiche absente peut être retiré.');
  const archived=await readdir(join(root,folders.archiveFolder,'Manuscript','Context'));
  assert.ok(archived.some(name=>name.includes('Structure')),'Originals du registre archivés.');
  assert.equal(await readFile(join(root,paths.chapter),'utf8'),'Nadia sort.','Aucune prose modifiée par le registre.');
  server=new ProjectMcp(async()=>'',undefined,undefined,undefined,undefined,undefined,undefined,undefined,async args=>JSON.stringify(structureView(await syncStructure(root,folders,args?{link:args}:{}),await projectSources(root,folders))));
  const url=await server.start();
  const rpc=async(method,params)=>{const response=await fetch(url,{method:'POST',headers:{Authorization:`Bearer ${server.token}`,'Content-Type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:1,method,params})});return (await response.json()).result;};
  const tools=await rpc('tools/list',{});
  assert.ok(tools.tools.some(tool=>tool.name===STRUCTURE_TOOL)); assert.ok(tools.tools.some(tool=>tool.name===LINK_TOOL));
  const read=await rpc('tools/call',{name:STRUCTURE_TOOL,arguments:{}}); assert.equal(read.isError,false);
  assert.ok(JSON.parse(read.content[0].text).nodes.some(item=>item.id===ids.seed));
  const denied=await rpc('tools/call',{name:LINK_TOOL,arguments:{...args('seed','plan','developpe'),decision:'retenu'}}); assert.equal(denied.isError,true);
  const removed=await rpc('tools/call',{name:LINK_TOOL,arguments:{...args('seed','plan','developpe'),remove:true}}); assert.equal(removed.isError,false);
  const invalid=structuredClone(data);invalid.nodes[1].id=invalid.nodes[0].id;
  assert.throws(()=>parseStructure(invalid,folders),/invalide/);
  await put(structurePath(folders),'```json\n'+JSON.stringify(invalid)+'\n```');
  await assert.rejects(()=>syncStructure(root,folders),/invalide/);
  assert.ok((await readFile(join(root,structurePath(folders)),'utf8')).includes(invalid.nodes[0].id));
 } finally { if(server) await server.stop(); await rm(root,{recursive:true,force:true}); }
}
