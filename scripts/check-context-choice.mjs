import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildSceneContext, checkSceneContext } from '../plugin/src/scene-context.ts';
import { readEditorialContext } from '../plugin/src/editorial-context.ts';
import { withContext, withoutContext, contextChoice, validateContextChoice } from '../plugin/src/request-context.ts';
import { selectionRequest, selectionPrompt, parseSelectionPrompt } from '../plugin/src/selection-actions.ts';
import { authorPrompt } from '../plugin/src/conversation.ts';
import { contextDelivery, collectChanges, deliverChanges, withChanges, withoutChanges } from '../plugin/src/workshop.ts';
import { DEFAULT_PROJECT_FOLDERS as folders } from '../plugin/src/settings.ts';
import { syncStructure } from '../plugin/src/story-structure.ts';
import { configPath } from '../plugin/src/narrative-context.ts';

export async function checkContextChoice() {
 const cwd=await mkdtemp(join(tmpdir(),'orelius-context-choice-'));
 const put=async(path,text)=>{await mkdir(join(cwd,path,'..'),{recursive:true});await writeFile(join(cwd,path),text);};
 const chapter='Manuscript/Chapitres/002.md',previous='Manuscript/Chapitres/001.md',scene='Manuscript/Scenes/cuisine.md',unused='Manuscript/Seeds/bateau.md',person='Bible/Personnages/Nadia.md',other='Bible/Personnages/Secret.md';
 try {
  for(const [path,text] of [[chapter,'Nadia entre dans la cuisine.'],[previous,'Nadia arrive.'],[scene,'Intention de la scène.'],[unused,'FICHE SANS RAPPORT'],[person,'Nadia est actrice.'],[other,'INFORMATION SECRÈTE'],['Bible/Style/Narration.md','Narration précise.']]) await put(path,text);
  let structure=await syncStructure(cwd,folders);
  const a=structure.nodes.find(node=>node.path===scene),b=structure.nodes.find(node=>node.path===chapter);
  await syncStructure(cwd,folders,{link:{from:a.id,to:b.id,relation:'realise',fromHash:a.hash,toHash:b.hash,quote:'Nadia entre',at:0}});
  let result=await buildSceneContext(cwd,folders,{},chapter,'Révise.');
  assert.ok(result.sources.some(source=>source.path===scene && source.reason.includes('Liée')));
  assert.ok(result.sources.some(source=>source.path===person));
  assert.ok(!result.sources.some(source=>source.path===unused));
  assert.ok(!result.pages.join('').includes('FICHE SANS RAPPORT'));
  const choice={chapter,include:[unused],exclude:[person,previous]};
  const request=withContext('Révise.',choice);
  assert.deepEqual(contextChoice(request),choice);assert.equal(withoutContext(request),'Révise.');
  assert.deepEqual(contextChoice(request+'\n\nUne précision.'),choice);
  assert.equal(withoutContext(request+'\n\nUne précision.'),'Révise.\n\nUne précision.');
  assert.equal(authorPrompt(request),'Révise.');
  assert.equal(authorPrompt('Message\n\n<!-- orelius:request-context -->\ninvalid'),'Message\n\n<!-- orelius:request-context -->\ninvalid');
  const selection=selectionRequest('reformuler',chapter,'Nadia entre',0,5);
  assert.deepEqual(parseSelectionPrompt(withContext(selectionPrompt(selection),choice)),parseSelectionPrompt(selectionPrompt(selection)));
  assert.equal(withoutChanges(withChanges(request,{pending:[]})),request);
  result=await buildSceneContext(cwd,folders,{[previous]:'Ancienne référence'},chapter,request);
  assert.ok(result.sources.some(source=>source.path===unused && source.reason.includes('explicite')));
  assert.ok(!result.sources.some(source=>source.path===person || source.path.startsWith(previous)));
  assert.ok(!result.pages.join('').includes('Nadia est actrice.'));
  await put(person,'Note exclue modifiée.');await checkSceneContext(cwd,result);
  await put(unused,'Note incluse modifiée.');await assert.rejects(checkSceneContext(cwd,result),/Source modifiée/);
  await assert.rejects(buildSceneContext(cwd,folders,{},chapter,withContext('x',{chapter,include:[],exclude:[chapter]})),/indispensable/);
  await assert.rejects(buildSceneContext(cwd,folders,{},chapter,withContext('x',{chapter:previous,include:[],exclude:[]})),/autre chapitre/);
  for(const path of ['../outside.md','/outside.md','Bible/../x.md']) assert.throws(()=>withContext('x',{chapter,include:[path],exclude:[]}));
  assert.throws(()=>validateContextChoice({chapter,include:['Archives/secret.md'],exclude:[]},folders,chapter),/hors/);
  assert.throws(()=>withContext('x',{chapter,include:[person],exclude:[person]}),/invalides/);
  await assert.rejects(buildSceneContext(cwd,folders,{},chapter,withContext('x',{chapter,include:['Bible/absent.md'],exclude:[]})),/absente/);
  const config={chapters:[],references:[{path:other,mode:'always'}],referenceBudget:1};
  await put(configPath(folders),'```json\n'+JSON.stringify(config)+'\n```');
  const preview=await buildSceneContext(cwd,folders,{},chapter,'',undefined,true);
  assert.ok(preview.sources.some(source=>source.path===other),'L’aperçu conserve la note obligatoire hors budget pour permettre son retrait.');
  await assert.rejects(buildSceneContext(cwd,folders,{},chapter),/hors budget/);
  result=await buildSceneContext(cwd,folders,{},chapter,withContext('',{chapter,include:[],exclude:[other,person]}));
  assert.ok(!result.sources.some(source=>source.path===other));
  await put(configPath(folders),'```json\n'+JSON.stringify({chapters:[],references:[]})+'\n```');
  const generic=await readEditorialContext(cwd,folders,{},undefined,withContext('Discute',{chapter:null,include:[other],exclude:['Bible/Style/Narration.md']}));
  assert.ok(generic.join('').includes('INFORMATION SECRÈTE'));assert.ok(!generic.join('').includes('Narration précise.'));
  const delivery=await collectChanges(cwd,folders);
  const scoped=contextDelivery(delivery,'',new Set([chapter]));
  assert.ok(scoped.pending.every(change=>change.path===chapter));
  const filtered=contextDelivery(delivery,withContext('',{chapter,include:[],exclude:[unused]}));
  assert.ok(delivery.pending.some(change=>change.path===unused));assert.ok(!filtered.pending.some(change=>change.path===unused));
  await deliverChanges(cwd,folders,filtered);
  assert.ok((await collectChanges(cwd,folders)).pending.some(change=>change.path===unused),'Une note écartée reste en attente pour une demande ultérieure.');
 } finally { await rm(cwd,{recursive:true,force:true}); }
}
